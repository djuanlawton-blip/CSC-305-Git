String? calculateGrade(int? score) {
  if (score == null || score < 0 || score > 100) {
    return 'Enter a number between 0 and 100';
  }

  if (score >= 90) {
    return 'A';
  } else if (score >= 80) {
    return 'B';
  } else if (score >= 70) {
    return 'C';
  } else if (score >= 60) {
    return 'D';
  } else {
    return 'F';
  }
}
